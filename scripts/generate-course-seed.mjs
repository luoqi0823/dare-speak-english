import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import { firstThirtyLessons, validateFirstThirtyLessons } from "../supabase/course-data/first-30-lessons.mjs";
import { getCourseIllustrationPath } from "../supabase/course-data/illustration-paths.mjs";

const errors = validateFirstThirtyLessons();
if (errors.length > 0) throw new Error(`课程数据校验失败：\n${errors.join("\n")}`);

const quote = (value) => value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const array = (values) => `array[${values.map(quote).join(", ")}]::text[]`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;

const rows = [];
for (const course of firstThirtyLessons) {
  const slug = `survival-${String(course.order).padStart(2, "0")}`;
  const lessonValues = [
    quote(slug), course.order, course.unitOrder, quote(course.unitTitle), quote(course.title), quote(course.scene),
    quote(`第 ${course.order} 个课程日：${course.scene}`), 6, quote("published"), "timezone('utc', now())",
    json(course.grammar), json(course.dialogue), quote(course.story.title), quote(course.story.english), quote(course.story.chinese), 1,
  ].join(", ");

  rows.push(`insert into public.lessons (slug, course_order, unit_order, unit_title, title, scene_title, summary, duration_minutes, status, published_at, grammar, dialogue, story_title, story_english, story_chinese, content_version)\nvalues (${lessonValues})\non conflict (slug) do update set\n  course_order = excluded.course_order, unit_order = excluded.unit_order, unit_title = excluded.unit_title,\n  title = excluded.title, scene_title = excluded.scene_title, summary = excluded.summary, duration_minutes = excluded.duration_minutes,\n  status = excluded.status, published_at = excluded.published_at, grammar = excluded.grammar, dialogue = excluded.dialogue,\n  story_title = excluded.story_title, story_english = excluded.story_english, story_chinese = excluded.story_chinese,\n  content_version = excluded.content_version, updated_at = timezone('utc', now());`);

  const items = [];
  course.words.forEach((word, index) => {
    items.push({ position: index + 1, kind: "word", ...word });
  });
  course.phrases.forEach((phrase, index) => {
    items.push({ position: index + 6, kind: "phrase", ...phrase, visual: "💬", mnemonic: "把整句话放进场景里说，不逐字翻译。" });
  });
  course.words.slice(0, 3).forEach((word, index) => {
    const distractors = [course.words[(index + 1) % 5].english, course.words[(index + 2) % 5].english];
    items.push({ position: index + 8, kind: "quiz", english: `单词回想 ${index + 1}`, chinese: word.chinese, visual: "✍️", mnemonic: null, prompt: `“${word.chinese}”的英文是什么？`, correctAnswer: word.english, distractors });
  });
  course.checks.forEach((check, index) => {
    items.push({ position: index + 11, kind: "comprehension", english: `文章理解 ${index + 1}`, chinese: "根据微文章选择答案", visual: "📖", mnemonic: null, prompt: check.prompt, correctAnswer: check.answer, distractors: check.distractors });
  });

  for (const item of items) {
    const imageKey = item.position <= 6
      ? getCourseIllustrationPath(course.order, item.position, item.english)
      : null;
    const values = [
      `(select id from public.lessons where slug = ${quote(slug)})`, item.position, quote(item.kind), quote(item.english), quote(item.chinese),
      "null", quote(imageKey), quote(item.visual), quote(item.mnemonic), quote(item.prompt), quote(item.correctAnswer), array(item.distractors ?? []),
    ].join(", ");
    rows.push(`insert into public.lesson_items (lesson_id, position, kind, english, chinese, phonetic, image_key, visual, mnemonic, prompt, correct_answer, distractors)\nvalues (${values})\non conflict (lesson_id, position) do update set\n  kind = excluded.kind, english = excluded.english, chinese = excluded.chinese, phonetic = excluded.phonetic,\n  image_key = excluded.image_key, visual = excluded.visual, mnemonic = excluded.mnemonic, prompt = excluded.prompt,\n  correct_answer = excluded.correct_answer, distractors = excluded.distractors, updated_at = timezone('utc', now());`);
  }
}

const header = `-- Generated by scripts/generate-course-seed.mjs. Do not edit by hand.\n-- 30 course days, 150 words, 60 phrases and 150 exercises.\nbegin;\n`;
const footer = `\ncommit;\n`;
const output = resolve(dirname(fileURLToPath(import.meta.url)), "../supabase/seed.sql");
await writeFile(output, `${header}${rows.join("\n\n")}${footer}`, "utf8");
console.log(`Generated ${output} with ${firstThirtyLessons.length} lessons and ${firstThirtyLessons.length * 12} lesson items.`);
