import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { firstThirtyLessons } from "../supabase/course-data/first-30-lessons.mjs";
import { getCourseIllustrationPath } from "../supabase/course-data/illustration-paths.mjs";

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const statements = [];

for (const course of firstThirtyLessons) {
  const lessonSlug = `survival-${String(course.order).padStart(2, "0")}`;
  const illustratedItems = [...course.words, course.phrases[0]];

  illustratedItems.forEach((item, index) => {
    const position = index + 1;
    const imageKey = getCourseIllustrationPath(course.order, position, item.english);
    statements.push(`update public.lesson_items
set image_key = ${quote(imageKey)}, updated_at = timezone('utc', now())
where lesson_id = (select id from public.lessons where slug = ${quote(lessonSlug)})
  and position = ${position};`);
  });
}

const output = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../supabase/migrations/20261023160000_flatten_course_illustration_paths.sql",
);
const sql = `-- Generated by scripts/generate-course-illustration-migration.mjs. Do not edit by hand.\nbegin;\n\n${statements.join("\n\n")}\n\ncommit;\n`;
await writeFile(output, sql, "utf8");
console.log(`Generated ${output} with ${statements.length} illustration keys.`);
